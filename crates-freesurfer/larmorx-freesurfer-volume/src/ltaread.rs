//! Reading a linear transform with its volume geometries (`utils/transform.cpp`, 3.1-39):
//! `LTAreadEx`, `LTAreadExType`, `TransformFileNameType`, and the readers they choose:
//! `ltaReadFileEx` (FreeSurfer's `.lta`), `ltaMNIreadEx` (MINC's `.xfm`, with `mincFindVolume`,
//! `mincGetVolumeInfo` and `mincGetVolInfo` for the volumes its comment names), `ltaFSLread` (an
//! FSL matrix) and `ltaReadRegisterDat` (a `register.dat`).
//!
//! A relative name is opened in `dir`, the program's working directory, when given (`CFile::open`'s
//! rule). Two functions of fs.io are the caller's ([`LtaIo`]): `MRIreadHeader` (for a volume an `.xfm`
//! names that exists) and `regio_read_register` (`registerio.cpp`, item 3.1-34).
//!
//! Defects (`larmorx_core::defects`; `docs/findings/freesurfer-volume.md` §7):
//! - **FS-306** (memory): `TransformFileNameType` copies the name into 500 bytes: a longer name
//!   writes past them. Both modes classify the whole name, noted.
//! - **FS-307** (a hang): `ltaMNIreadEx` skips the lines starting with `%` after its second line
//!   until another one; a file whose last line starts with `%` keeps it and loops forever. An
//!   error here in both modes.
//! - **FS-308** (memory): `ltaReadFileEx` takes the type and the number of transforms from its first
//!   two lines without a value when they do not match `type = <n>` and `nxforms = <n>`: memory
//!   contents. Both modes take 0, noted.
//! - **FS-309** (crash): `ltaReadFileEx` of a file of one line reads its missing second line
//!   (`sscanf` of `NULL`). An error here in both modes.
//! - **FS-310** (crash): `mincFindVolume` of a `%Generated by` line whose last word contains `src`
//!   or `dst` takes the word after it, which is not there. An error here in both modes.

