/// What `regio_read_register` gives: the subject, the in-plane and between-plane resolutions, the
/// intensity (`fscale`), the matrix and the float-to-int method.
pub struct RegisterDat {
    pub subject: Vec<u8>,
    pub inplaneres: f32,
    pub betplaneres: f32,
    pub intensity: f32,
    pub r: Matrix,
    pub float2int: i32,
}

/// fs.io's functions the readers call (track A's `mriio.cpp` and `registerio.cpp`).
pub trait LtaIo {
    /// `MRIreadHeader(name, MRI_VOLUME_TYPE_UNKNOWN)`: the volume's geometry, or `None` for `NULL`
    /// (its messages written as it writes them).
    fn read_header(
        &mut self,
        g: &mut Globals,
        out: &mut dyn Write,
        err: &mut dyn Write,
        dir: Option<&Path>,
        name: &str,
    ) -> Result<Option<VolGeom>, Fatal>;
    /// `regio_read_register(name, ...)`: the register file, or `None` when it returns an error.
    fn read_register(
        &mut self,
        g: &mut Globals,
        out: &mut dyn Write,
        err: &mut dyn Write,
        dir: Option<&Path>,
        name: &str,
    ) -> Result<Option<RegisterDat>, Fatal>;
}

/// A C string's bytes (up to its first NUL).
fn c_str(b: &[u8]) -> &[u8] {
    &b[..b.iter().position(|&c| c == 0).unwrap_or(b.len())]
}

/// `TransformFileNameType(fname)`: by the extension after the last `@` (or, without one, the last
/// `.`), the name cut at its first `#` (an `@` after the `#` still counts, its text not upper-cased):
/// a name ending in `nii.gz` (case as written, more than 6 bytes) and `M3D`, `M3Z`, `MGZ`, `NII`
/// `MORPH_3D_TYPE`; `OCT` and `LTA` `TRANSFORM_ARRAY_TYPE`; `XFM` `MNI_TRANSFORM_TYPE`; `FSLMAT`
/// `FSLREG_TYPE`; any other extension `REGISTER_DAT`; none `TRANSFORM_ARRAY_TYPE` (FS-306 for 500
/// bytes or more).
pub fn transform_file_name_type(g: &mut Globals, fname: &[u8]) -> i32 {
    let mut buf = c_str(fname).to_vec();
    if buf.len() >= 500 {
        g.notices.add(
            &FS_306,
            "TransformFileNameType of a name of 500 bytes or more (its buffer overflows)",
        );
    }
    let at = buf.iter().rposition(|&c| c == b'@');
    let end = match buf.iter().position(|&c| c == b'#') {
        Some(h) => {
            buf[h] = 0;
            h
        }
        None => buf.len(),
    };
    if end > 6 && &buf[end - 6..end] == b"nii.gz" {
        return MORPH_3D_TYPE;
    }
    let dot = at.or_else(|| buf[..end].iter().rposition(|&c| c == b'.'));
    let Some(dot) = dot else {
        return TRANSFORM_ARRAY_TYPE;
    };
    buf[..end].make_ascii_uppercase();
    let ext = c_str(&buf[dot + 1..]);
    match ext {
        b"M3D" | b"M3Z" | b"MGZ" | b"NII" => MORPH_3D_TYPE,
        b"OCT" | b"LTA" => TRANSFORM_ARRAY_TYPE,
        b"XFM" => MNI_TRANSFORM_TYPE,
        b"FSLMAT" => FSLREG_TYPE,
        _ => REGISTER_DAT,
    }
}

/// `LTAreadEx(fname)`: [`lta_read_ex_type`] with [`transform_file_name_type`]'s type.
pub fn lta_read_ex(
    g: &mut Globals,
    out: &mut dyn Write,
    err: &mut dyn Write,
    dir: Option<&Path>,
    fname: &str,
    io: &mut dyn LtaIo,
) -> Result<Option<Lta>, Fatal> {
    let t = transform_file_name_type(g, fname.as_bytes());
    lta_read_ex_type(g, out, err, dir, fname, t, io)
}

/// `LTAreadExType(fname, type)`: a name whose file part is `identity.nofile` gives an identity
/// `LINEAR_RAS_TO_RAS` transform (no file read); else `FSLREG_TYPE` an FSL matrix
/// ([`lta_fsl_read`]), `REGISTER_DAT` a `register.dat` (`INFO: This REGISTER_DAT transform is valid
/// only for volumes between  COR types with c_(r,a,s) = 0.` on standard output first), `MNI_TRANSFORM_TYPE`
/// an `.xfm` ([`lta_mni_read_ex`]), any other type an `.lta` ([`lta_read_file_ex`]).
pub fn lta_read_ex_type(
    g: &mut Globals,
    out: &mut dyn Write,
    err: &mut dyn Write,
    dir: Option<&Path>,
    fname: &str,
    ty: i32,
    io: &mut dyn LtaIo,
) -> Result<Option<Lta>, Fatal> {
    if file_name_only(fname) == "identity.nofile" {
        let mut lta = lta_alloc(g, out, err, 1, None)?;
        lta.ltype = LINEAR_RAS_TO_RAS;
        let Ret::New(id) = matrix_identity(g, out, err, 4, None)? else {
            unreachable!("MatrixIdentity without an output returns a new matrix")
        };
        lta.xforms[0].m_l = Some(id);
        lta.xforms[0].ltype = lta.ltype;
        return Ok(Some(lta));
    }
    match ty {
        FSLREG_TYPE => lta_fsl_read(g, out, err, dir, fname),
        REGISTER_DAT => {
            let _ = out.write_all(
                b"INFO: This REGISTER_DAT transform is valid only for volumes between  COR types with c_(r,a,s) = 0.\n",
            );
            lta_read_register_dat(g, out, err, dir, fname, io)
        }
        MNI_TRANSFORM_TYPE => lta_mni_read_ex(g, out, err, dir, fname, io),
        _ => lta_read_file_ex(g, out, err, dir, fname),
    }
}

/// `fopen(fname, "r")` with `errno` set on failure.
fn open(g: &mut Globals, dir: Option<&Path>, fname: &str) -> Option<CFile> {
    match CFile::open(dir, fname, "r") {
        Ok(f) => Some(f),
        Err(e) => {
            g.errno = e;
            None
        }
    }
}

/// `fgetl(line, n, fp)` with its buffer: `line` holds what the last `fgets` read, as `fgetl`
/// leaves it (the line from the first non-space byte cut at its first `#` and without its
/// newline; the bytes before kept); the offset of `fgetl`'s result in it, `None` at the end of the
/// file (the buffer as the last read left it).
fn fgetl_buf(fp: &mut CFile, n: usize, line: &mut Vec<u8>) -> Option<usize> {
    loop {
        let got = fp.fgets(n)?;
        *line = c_str(&got).to_vec();
        let start = line
            .iter()
            .position(|&b| !is_space(b))
            .unwrap_or(line.len());
        if start == line.len() || line[start] == b'#' || line[start] == b'\n' {
            continue;
        }
        if let Some(h) = line[start..].iter().position(|&b| b == b'#') {
            line.truncate(start + h);
        }
        if line.last() == Some(&b'\n') {
            line.pop();
        }
        return Some(start);
    }
}

/// `sscanf(cp, "%f %f %f %f", row of m)`: the numbers read until one is missing.
fn scan_row(g: &mut Globals, cp: &[u8], m: &mut Matrix, row: i32) {
    let mut b = Bytes::new(cp);
    let mut call = Call::new();
    for col in 1..=4 {
        let Some(v) = call.f32(&mut b, &mut g.errno) else {
            return;
        };
        m.set_relt(row, col, v);
    }
}

/// `ltaFSLread(fname)`: a one-transform LTA (`sigma` 1, centre 0) whose matrix's first three rows
/// are the file's first three lines that are not blank or comments (`fgetl`, 900 bytes; `%f %f %f
/// %f`), of type `FSLREG_TYPE`. Errors (`NULL`): `ltFSLread: could not open file <fname>`
/// (`ERROR_NOFILE`), `ltFSLread: could not read row <r> from <fname>` (`ERROR_BADFILE`).
pub fn lta_fsl_read(
    g: &mut Globals,
    out: &mut dyn Write,
    err: &mut dyn Write,
    dir: Option<&Path>,
    fname: &str,
) -> Result<Option<Lta>, Fatal> {
    let Some(mut fp) = open(g, dir, fname) else {
        log::error_printf(
            g,
            err,
            ERROR_NOFILE,
            &format!("ltFSLread: could not open file {fname}"),
        );
        return Ok(None);
    };
    let mut lta = lta_alloc(g, out, err, 1, None)?;
    let lt = &mut lta.xforms[0];
    lt.sigma = 1.0;
    (lt.x0, lt.y0, lt.z0) = (0.0, 0.0, 0.0);
    let mut line = Vec::new();
    for row in 1..=3 {
        let Some(at) = fgetl_buf(&mut fp, 900, &mut line) else {
            log::error_printf(
                g,
                err,
                ERROR_BADFILE,
                &format!("ltFSLread: could not read row {row} from {fname}"),
            );
            return Ok(None);
        };
        let m = lta.xforms[0].m_l.as_mut().expect("LTAalloc's matrix");
        scan_row(g, &line[at..], m, row);
    }
    lta.ltype = FSLREG_TYPE;
    Ok(Some(lta))
}

/// `ltaMNIreadEx(fname)`: a MINC `.xfm`. The first line (`fgetl`, 900 bytes, as every line here)
/// must start with `MNI Transform File`; a second line starting with `%` is the volume
/// information, else the volumes are not looked for (and a line starting with `Transform_Type`
/// moves straight to the matrix after the next line); a third line starting with `%` is the second
/// information line, the following `%` lines skipped and one more line read (a `Transform_Type`
/// line there again moves to the matrix after the next line); then three rows `%f %f %f %f`. With
/// volume information, the source and destination geometries from [`minc_get_vol_info`]. Type
/// `LINEAR_RAS_TO_RAS`. Errors (`NULL`): `ltMNIreadEx: could not open file <fname>`,
/// `ltMNIreadEx:<fname> does not start as 'MNI Transform File'` (`ERROR_NOFILE`), `ltMNIreadEx:
/// could not read row <r> from <fname> (<the last line read>)` (`ERROR_BADFILE`); FS-307.
pub fn lta_mni_read_ex(
    g: &mut Globals,
    out: &mut dyn Write,
    err: &mut dyn Write,
    dir: Option<&Path>,
    fname: &str,
    io: &mut dyn LtaIo,
) -> Result<Option<Lta>, Fatal> {
    let Some(mut fp) = open(g, dir, fname) else {
        log::error_printf(
            g,
            err,
            ERROR_NOFILE,
            &format!("ltMNIreadEx: could not open file {fname}"),
        );
        return Ok(None);
    };
    let mut lta = lta_alloc(g, out, err, 1, None)?;
    {
        let lt = &mut lta.xforms[0];
        lt.sigma = 1.0;
        (lt.x0, lt.y0, lt.z0) = (0.0, 0.0, 0.0);
    }
    let (mut line, mut info, mut info2) = (Vec::new(), Vec::new(), Vec::new());
    let mut no_volinfo = false;
    fgetl_buf(&mut fp, 900, &mut line);
    if !line.starts_with(b"MNI Transform File") {
        log::error_printf(
            g,
            err,
            ERROR_NOFILE,
            &format!("ltMNIreadEx:{fname} does not start as 'MNI Transform File'"),
        );
        return Ok(None);
    }
    let first = |l: &[u8]| l.first().copied();
    'header: {
        fgetl_buf(&mut fp, 900, &mut line);
        if first(&line) == Some(b'%') {
            info = line.clone();
        } else {
            no_volinfo = true;
            if line.starts_with(b"Transform_Type") {
                fgetl_buf(&mut fp, 900, &mut line);
                break 'header;
            }
        }
        fgetl_buf(&mut fp, 900, &mut line);
        if first(&line) == Some(b'%') {
            info2 = line.clone();
            while first(&line) == Some(b'%') {
                if fgetl_buf(&mut fp, 900, &mut line).is_none() {
                    g.notices.add(
                        &FS_307,
                        "ltMNIreadEx of a file whose last line starts with %",
                    );
                    log::error_exit(
                        g,
                        err,
                        ERROR_BADFILE,
                        &format!(
                            "ltMNIreadEx: {fname} ends with a % line (FreeSurfer never returns here)\n"
                        ),
                    )?;
                    return Ok(None);
                }
            }
            fgetl_buf(&mut fp, 900, &mut line);
            if line.starts_with(b"Transform_Type") {
                fgetl_buf(&mut fp, 900, &mut line);
            }
        } else if line.starts_with(b"Transform_Type") {
            fgetl_buf(&mut fp, 900, &mut line);
        }
    }
    for row in 1..=3 {
        let Some(at) = fgetl_buf(&mut fp, 900, &mut line) else {
            let shown = String::from_utf8_lossy(&line).into_owned();
            log::error_printf(
                g,
                err,
                ERROR_BADFILE,
                &format!("ltMNIreadEx: could not read row {row} from {fname} ({shown})"),
            );
            return Ok(None);
        };
        let m = lta.xforms[0].m_l.as_mut().expect("LTAalloc's matrix");
        scan_row(g, &line[at..], m, row);
    }
    drop(fp);
    if !no_volinfo {
        let (mut src, mut dst) = (lta.xforms[0].src.clone(), lta.xforms[0].dst.clone());
        minc_get_vol_info(g, out, err, dir, &info, &info2, &mut src, &mut dst, io)?;
        lta.xforms[0].src = src;
        lta.xforms[0].dst = dst;
    }
    lta.ltype = LINEAR_RAS_TO_RAS;
    Ok(Some(lta))
}

/// `strtok`'s words of a line (separated by blanks only).
fn words(l: &[u8]) -> Vec<&[u8]> {
    l.split(|&c| c == b' ').filter(|w| !w.is_empty()).collect()
}

fn contains(hay: &[u8], needle: &[u8]) -> bool {
    hay.windows(needle.len()).any(|w| w == needle)
}

/// `mincFindVolume(line, line2, &src, &dst)`: the volumes a `.xfm`'s comment lines name. A line
/// with `%Generated by` (FreeSurfer's): the word after the first word containing `src` is the
/// source, after the first containing `dst` the destination (1 then; FS-310 when the word is
/// missing). Else a `minctracc` line: the first two words containing `.mnc` are the source and the
/// destination (1; a line with one leaves the next call's first `.mnc` word as the destination:
/// FreeSurfer's static count, `Globals::minc_find_volume_count`); else MINC's GUI lines: the second
/// word of `line` the destination, of `line2` the source, each when it contains `.mnc`. With
/// `Gdiag`'s `DIAG_VERBOSE`, `INFO: Src volume <v>` and `INFO: Target volume <v>` on standard output.
#[allow(clippy::type_complexity)]
pub fn minc_find_volume(
    g: &mut Globals,
    out: &mut dyn Write,
    err: &mut dyn Write,
    line: &[u8],
    line2: &[u8],
) -> Result<(i32, Option<Vec<u8>>, Option<Vec<u8>>), Fatal> {
    let verbose = g.gdiag & DIAG_VERBOSE != 0;
    let (mut src, mut dst) = (None, None);
    let w = words(line);
    if !contains(line, b"%Generated by") {
        if contains(line, b"minctracc") {
            for t in w {
                if contains(t, b".mnc") {
                    if g.minc_find_volume_count == 0 {
                        g.minc_find_volume_count += 1;
                        if verbose {
                            let _ = out.write_all(&[b"INFO: Src volume ", t, b"\n"].concat());
                        }
                        src = Some(t.to_vec());
                    } else if g.minc_find_volume_count == 1 {
                        if verbose {
                            let _ = out.write_all(&[b"INFO: Target volume ", t, b"\n"].concat());
                        }
                        g.minc_find_volume_count = 0;
                        return Ok((1, src, Some(t.to_vec())));
                    }
                }
            }
        } else {
            if let Some(t) = w.get(1) {
                if contains(t, b".mnc") {
                    dst = Some(t.to_vec());
                }
                if let Some(t2) = words(line2).get(1)
                    && contains(t2, b".mnc")
                {
                    src = Some(t2.to_vec());
                }
            }
            if verbose {
                if let Some(s) = &src {
                    let _ = out.write_all(&[b"INFO: Src volume ", s.as_slice(), b"\n"].concat());
                }
                if let Some(d) = &dst {
                    let _ = out.write_all(&[b"INFO: Target volume ", d.as_slice(), b"\n"].concat());
                }
            }
        }
        return Ok((0, src, dst));
    }
    let mut i = 0;
    while i < w.len() {
        let t = w[i];
        let is_src = contains(t, b"src");
        if is_src || contains(t, b"dst") {
            let Some(next) = w.get(i + 1) else {
                g.notices.add(
                    &FS_310,
                    "mincFindVolume of a %Generated by line whose last word names src or dst",
                );
                log::error_exit(
                    g,
                    err,
                    ERROR_BADFILE,
                    "mincFindVolume: no word after src or dst (FreeSurfer crashes here)\n",
                )?;
                return Ok((0, src, dst));
            };
            let label: &[u8] = if is_src {
                b"INFO: Src volume "
            } else {
                b"INFO: Target volume "
            };
            if verbose {
                let _ = out.write_all(&[label, next, b"\n"].concat());
            }
            if is_src {
                src = Some(next.to_vec());
            } else {
                return Ok((1, src, Some(next.to_vec())));
            }
            i += 2;
        } else {
            i += 1;
        }
    }
    Ok((0, src, dst))
}

/// The geometry of MNI's `average_305` (`mincGetVolumeInfo`, `mincGetVolInfo`).
fn average_305(vg: &mut VolGeom) {
    (vg.width, vg.height, vg.depth) = (172, 220, 156);
    (vg.xsize, vg.ysize, vg.zsize) = (1.0, 1.0, 1.0);
    (vg.x_r, vg.x_a, vg.x_s) = (1.0, 0.0, 0.0);
    (vg.y_r, vg.y_a, vg.y_s) = (0.0, 1.0, 0.0);
    (vg.z_r, vg.z_a, vg.z_s) = (0.0, 0.0, 1.0);
    (vg.c_r, vg.c_a, vg.c_s) = (-0.0950, -16.5100, 9.7500);
    vg.valid = 1;
}

/// `mincGetVolumeInfo(vol, vg)`: a named volume that exists gives its geometry (`MRIreadHeader`,
/// [`LtaIo::read_header`]; `initVolGeom` when it gives `NULL`); one that does not (`stat` fails,
/// `errno` kept) and whose name contains `average_305` MNI's average brain's geometry (`INFO: The
/// transform was made with average_305.mnc.` with `DIAG_SHOW` and `DIAG_VERBOSE`), else
/// `initVolGeom`; no name `initVolGeom`. The name (or `unknown`) copied into the geometry.
pub fn minc_get_volume_info(
    g: &mut Globals,
    out: &mut dyn Write,
    err: &mut dyn Write,
    dir: Option<&Path>,
    vol: Option<&[u8]>,
    vg: &mut VolGeom,
    io: &mut dyn LtaIo,
) -> Result<(), Fatal> {
    match vol {
        Some(name) => {
            let path = String::from_utf8_lossy(name).into_owned();
            let full = match dir {
                Some(d) if !Path::new(&path).is_absolute() => d.join(&path),
                _ => Path::new(&path).to_path_buf(),
            };
            match std::fs::metadata(&full) {
                Err(e) => {
                    g.errno = e.raw_os_error().unwrap_or(2);
                    if contains(name, b"average_305") {
                        if g.gdiag & DIAG_SHOW != 0 && g.gdiag & DIAG_VERBOSE != 0 {
                            let _ = out
                                .write_all(b"INFO: The transform was made with average_305.mnc.\n");
                        }
                        average_305(vg);
                    } else {
                        init_vol_geom(vg);
                    }
                }
                Ok(_) => match io.read_header(g, out, err, dir, &path)? {
                    Some(h) => get_vol_geom(&h, vg),
                    None => init_vol_geom(vg),
                },
            }
            vg.fname.strcpy_bytes(name);
        }
        None => {
            init_vol_geom(vg);
            vg.fname.strcpy_bytes(b"unknown");
        }
    }
    Ok(())
}

/// `mincGetVolInfo(infoline, infoline2, vgSrc, vgDst)`: [`minc_find_volume`]'s volumes through
/// [`minc_get_volume_info`]; a destination without a valid geometry takes `average_305`'s when the
/// environment has `USE_AVERAGE305` (`INFO: using average_305 info, since ` and `INFO: environment
/// var USE_AVERAGE305 set` on standard error).
#[allow(clippy::too_many_arguments)]
pub fn minc_get_vol_info(
    g: &mut Globals,
    out: &mut dyn Write,
    err: &mut dyn Write,
    dir: Option<&Path>,
    info: &[u8],
    info2: &[u8],
    src: &mut VolGeom,
    dst: &mut VolGeom,
    io: &mut dyn LtaIo,
) -> Result<(), Fatal> {
    let (_, s, d) = minc_find_volume(g, out, err, info, info2)?;
    minc_get_volume_info(g, out, err, dir, s.as_deref(), src, io)?;
    minc_get_volume_info(g, out, err, dir, d.as_deref(), dst, io)?;
    if dst.valid == 0 && std::env::var_os("USE_AVERAGE305").is_some() {
        let _ = err.write_all(b"INFO: using average_305 info, since \n");
        let _ = err.write_all(b"INFO: environment var USE_AVERAGE305 set\n");
        average_305(dst);
    }
    Ok(())
}

/// A white-space-separated format's literal text matched on a stream (`scanf`'s directives): white
/// space skips any, any other byte must come next; false at the first that does not.
fn lit(st: &mut dyn Stream, text: &[u8]) -> bool {
    for &c in text {
        if is_space(c) {
            skip_space(st);
        } else if st.peek() == Some(c) {
            st.bump();
        } else {
            return false;
        }
    }
    true
}

/// `sscanf`'s `%s`: skips white space, then the word (`None` at the end of the input).
fn word<'a>(b: &mut Bytes<'a>) -> Option<&'a [u8]> {
    skip_space(b);
    let s = b.i;
    while b.peek().is_some_and(|c| !is_space(c)) {
        b.bump();
    }
    (b.i > s).then(|| &b.s[s..b.i])
}

/// `%d` after a literal (`sscanf(cp, "<text> %d\n", &v)`).
fn lit_int(g: &mut Globals, cp: &[u8], text: &[u8]) -> Option<i32> {
    let mut b = Bytes::new(cp);
    if !lit(&mut b, text) {
        return None;
    }
    Call::new().i32(&mut b, &mut g.errno)
}

/// A `FILE *` as `std::io::BufRead` (one byte of lookahead), for the readers written on it.
struct Buffered<'a>(&'a mut CFile, [u8; 1]);

impl Read for Buffered<'_> {
    fn read(&mut self, buf: &mut [u8]) -> std::io::Result<usize> {
        let n = self.fill_buf()?.len().min(buf.len());
        if n > 0 {
            buf[0] = self.1[0];
            self.consume(1);
        }
        Ok(n)
    }
}

impl BufRead for Buffered<'_> {
    fn fill_buf(&mut self) -> std::io::Result<&[u8]> {
        match self.0.peek() {
            Some(c) => {
                self.1[0] = c;
                Ok(&self.1[..])
            }
            None => Ok(&[]),
        }
    }
    fn consume(&mut self, n: usize) {
        for _ in 0..n {
            self.0.bump();
        }
    }
}

/// `ltaReadFileEx(fname)`: FreeSurfer's `.lta`: `type = <n>` and `nxforms = <n>` from the first two
/// lines (`fgetl`, 1023 bytes; FS-308, FS-309), then for each transform `mean = %f %f %f`, `sigma =
/// %f` (`fscanf`) and the matrix (`MatrixAsciiReadFrom`); then for each transform a line (`fgets`)
/// starting with `src volume info` reads the source's geometry (`readVolGeom`) and a following
/// `dst volume info` the destination's; then `subject <word>` and `fscale <f>` lines anywhere after
/// (the subject empty and `fscale` 0.15 otherwise). Errors (`NULL`, `ERROR_BADFILE`):
/// `ltaReadFile(<fname>): can't open file`, `ltaReadFile(<fname>): can't read data`.
pub fn lta_read_file_ex(
    g: &mut Globals,
    out: &mut dyn Write,
    err: &mut dyn Write,
    dir: Option<&Path>,
    fname: &str,
) -> Result<Option<Lta>, Fatal> {
    let Some(mut fp) = open(g, dir, fname) else {
        log::error_printf(
            g,
            err,
            ERROR_BADFILE,
            &format!("ltaReadFile({fname}): can't open file"),
        );
        return Ok(None);
    };
    let mut line = Vec::new();
    let Some(at) = fgetl_buf(&mut fp, STRLEN - 1, &mut line) else {
        log::error_printf(
            g,
            err,
            ERROR_BADFILE,
            &format!("ltaReadFile({fname}): can't read data"),
        );
        return Ok(None);
    };
    let ty = lit_int(g, &line[at..], b"type      = ");
    let Some(at) = fgetl_buf(&mut fp, STRLEN - 1, &mut line) else {
        g.notices
            .add(&FS_309, "ltaReadFile of a file without a second line");
        log::error_exit(
            g,
            err,
            ERROR_BADFILE,
            &format!("ltaReadFile({fname}): no second line (FreeSurfer crashes here)\n"),
        )?;
        return Ok(None);
    };
    let nx = lit_int(g, &line[at..], b"nxforms   = ");
    if ty.is_none() || nx.is_none() {
        g.notices.add(
            &FS_308,
            "ltaReadFile without type = <n> or nxforms = <n>: a value never set (taken as 0)",
        );
    }
    let mut lta = lta_alloc(g, out, err, nx.unwrap_or(0), None)?;
    lta.ltype = ty.unwrap_or(0);
    for i in 0..lta.xforms.len() {
        let lt = &mut lta.xforms[i];
        let mut call = Call::new();
        if lit(&mut fp, b"mean      = ") {
            let mut all = true;
            for v in [&mut lt.x0, &mut lt.y0, &mut lt.z0] {
                match call.f32(&mut fp, &mut g.errno) {
                    Some(x) => *v = x,
                    None => {
                        all = false;
                        break;
                    }
                }
            }
            if all {
                skip_space(&mut fp);
            }
        }
        let mut call = Call::new();
        if lit(&mut fp, b"sigma     = ")
            && let Some(x) = call.f32(&mut fp, &mut g.errno)
        {
            lt.sigma = x;
            skip_space(&mut fp);
        }
        let mut m = lt.m_l.take();
        {
            let mut r = Buffered(&mut fp, [0]);
            matrix_ascii_read_from(g, out, err, &mut r, m.as_mut())?;
        }
        lta.xforms[i].m_l = m;
    }
    for i in 0..lta.xforms.len() {
        if let Some(l) = fp.fgets(STRLEN - 1) {
            line = c_str(&l).to_vec();
            if line.starts_with(b"src volume info") {
                if g.gdiag & DIAG_VERBOSE != 0 {
                    let _ = err.write_all(b"INFO: src volume info present\n");
                }
                read_vol_geom(g, err, &mut fp, &mut lta.xforms[i].src);
                if let Some(l) = fp.fgets(STRLEN - 1) {
                    line = c_str(&l).to_vec();
                }
                if line.starts_with(b"dst volume info") {
                    if g.gdiag & DIAG_VERBOSE != 0 {
                        let _ = err.write_all(b"INFO: dst volume info present\n");
                    }
                    read_vol_geom(g, err, &mut fp, &mut lta.xforms[i].dst);
                }
            }
        }
    }
    lta.subject.memset0(1);
    lta.fscale = 0.15f64 as f32;
    while let Some(l) = fp.fgets(STRLEN - 1) {
        let l = c_str(&l).to_vec();
        if l.starts_with(b"subject") {
            let mut b = Bytes::new(&l);
            if word(&mut b).is_some()
                && let Some(s) = word(&mut b)
            {
                lta.subject.strcpy_bytes(s);
            }
        } else if l.starts_with(b"fscale") {
            let mut b = Bytes::new(&l);
            if word(&mut b).is_some()
                && let Some(x) = Call::new().f32(&mut b, &mut g.errno)
            {
                lta.fscale = x;
            }
        }
    }
    Ok(Some(lta))
}

/// `ltaReadRegisterDat(fname, NULL, NULL)`: a one-transform LTA (`sigma` 1) from
/// `regio_read_register` ([`LtaIo::read_register`]): its subject, its intensity as `fscale`, its
/// matrix; the source geometry not valid with sizes (in-plane, in-plane, between-plane), the
/// destination's not valid with sizes 1; type `REGISTER_DAT`. A register that cannot be read gives
/// the error `ltaReadRegisterDat: could not read <fname>` (`ERROR_BADPARM`) and `NULL`.
pub fn lta_read_register_dat(
    g: &mut Globals,
    out: &mut dyn Write,
    err: &mut dyn Write,
    dir: Option<&Path>,
    fname: &str,
    io: &mut dyn LtaIo,
) -> Result<Option<Lta>, Fatal> {
    let mut lta = lta_alloc(g, out, err, 1, None)?;
    lta.xforms[0].sigma = 1.0;
    let Some(reg) = io.read_register(g, out, err, dir, fname)? else {
        log::error_printf(
            g,
            err,
            ERROR_BADPARM,
            &format!("ltaReadRegisterDat: could not read {fname}"),
        );
        return Ok(None);
    };
    lta.fscale = reg.intensity;
    lta.subject.strcpy_bytes(&reg.subject);
    matrix_copy(g, out, err, Some(&reg.r), lta.xforms[0].m_l.as_mut())?;
    let src = &mut lta.xforms[0].src;
    src.valid = 0;
    (src.xsize, src.ysize, src.zsize) = (reg.inplaneres, reg.inplaneres, reg.betplaneres);
    let dst = &mut lta.xforms[0].dst;
    dst.valid = 0;
    (dst.xsize, dst.ysize, dst.zsize) = (1.0, 1.0, 1.0);
    lta.ltype = REGISTER_DAT;
    Ok(Some(lta))
}
