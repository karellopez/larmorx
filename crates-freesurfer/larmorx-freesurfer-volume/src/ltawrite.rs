//! Writing a linear transform array (`utils/transform.cpp`, 3.1-39): `LTAwrite` (687) and
//! `LTAwriteEx` (3280) with the writers they choose by the name's extension and the array's type:
//! `ltaMNIwrite` (1663, MINC's `.xfm`), fs.io's `regio_write_register` (a `register.dat`),
//! `ltaFSLwrite` (1626, an FSL matrix) and FreeSurfer's own `.lta` (a header and `LTAprint`);
//! `LTAread` (700: `LTAreadEx`, the code after its `return` never runs) and `LTAdumpVolGeom`
//! (4221).
//!
//! A relative name is opened in `dir`, the program's working directory, when given (`CFile::open`'s
//! rule). The environment (`USER`, `LOGNAME`, `FREESURFER_REPLACEMENT_FOR_CREATION_TIME_STRING`
//! and the FSL conversion's `FSLOUTPUTTYPE`) is the program's, never the process's.
//!
//! Defects (`larmorx_core::defects`): FS-504 (memory, crash): an array without transforms, or a
//! first transform without a matrix of at least 3 x 4 (4 x 4 for the FSL and MINC writers), where a
//! writer reads one: an error in both modes (the `.lta` writer's own reads are `LTAprint`'s).

