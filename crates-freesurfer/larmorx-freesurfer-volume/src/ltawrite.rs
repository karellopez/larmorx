/// `fopen(fname, "w")` with `errno` set on failure.
fn create(g: &mut Globals, dir: Option<&Path>, fname: &str) -> Option<CFile> {
    match CFile::open(dir, fname, "w") {
        Ok(f) => Some(f),
        Err(e) => {
            g.errno = e;
            None
        }
    }
}

/// The first transform's matrix when it has at least `rows` x `cols` elements; FS-504 otherwise
/// (what FreeSurfer reads there is memory it does not own).
fn first_matrix<'a>(
    g: &mut Globals,
    err: &mut dyn Write,
    what: &str,
    lta: &'a Lta,
    rows: i32,
    cols: i32,
) -> Result<Option<&'a Matrix>, Fatal> {
    let Some(lt) = lta.xforms.first().filter(|_| lta.num_xforms > 0) else {
        outside(g, err, what, "an array without transforms")?;
        return Ok(None);
    };
    match lt.m_l.as_ref().filter(|m| m.rows >= rows && m.cols >= cols) {
        Some(m) => Ok(Some(m)),
        None => {
            outside(g, err, what, "a transform without its matrix")?;
            Ok(None)
        }
    }
}

/// `%13.8f` and the separator after it.
fn f13(s: &mut Vec<u8>, v: f32, sep: &[u8]) {
    s.extend_from_slice(fmt_f(f64::from(v), 13, 8).as_bytes());
    s.extend_from_slice(sep);
}

/// The three rows `ltaMNIwrite` writes of `m`: four `%13.8f` numbers each with a space after,
/// `;` after the third row, a newline after each.
fn mni_rows(s: &mut Vec<u8>, m: &Matrix) {
    for row in 1..=3 {
        for col in 1..=4 {
            f13(s, m.relt(row, col), b" ");
        }
        if row == 3 {
            s.push(b';');
        }
        s.push(b'\n');
    }
}

/// `ltaMNIwrite(lta, fname)`: `MNI Transform File`, `%Generated by <program> src <name> dst
/// <name>` (the first transform's geometries' file names), an empty line, `Transform_Type =
/// Linear;` and `Linear_Transform =`, then the first transform's RAS-to-RAS matrix's three rows:
/// the matrix itself for `LINEAR_RAS_TO_RAS` and `MNI_TRANSFORM_TYPE`, for `LINEAR_VOX_TO_VOX` the
/// destination's voxel-to-RAS times the matrix times the source's RAS-to-voxel (`float`
/// products, the left one first), for any other type none. `NO_ERROR`; a file that cannot be
/// created: `ltaMNIwrite: could not open file <name>` as an error, `ERROR_NOFILE`. FS-504.
fn lta_mni_write(
    g: &mut Globals,
    out: &mut dyn Write,
    err: &mut dyn Write,
    dir: Option<&Path>,
    lta: &Lta,
    fname: &str,
) -> Result<i32, Fatal> {
    let Some(mut fp) = create(g, dir, fname) else {
        log::error_printf(
            g,
            err,
            ERROR_NOFILE,
            &format!("ltaMNIwrite: could not open file {fname}"),
        );
        return Ok(ERROR_NOFILE);
    };
    let mut s: Vec<u8> = b"MNI Transform File\n".to_vec();
    if lta.num_xforms <= 0 || lta.xforms.is_empty() {
        outside(g, err, "ltaMNIwrite", "an array without transforms")?;
        return Ok(ERROR_BADPARM);
    }
    let lt = &lta.xforms[0];
    s.extend_from_slice(b"%Generated by ");
    s.extend_from_slice(g.progname.as_bytes());
    s.extend_from_slice(b" src ");
    s.extend_from_slice(lt.src.fname.c_bytes());
    s.extend_from_slice(b" dst ");
    s.extend_from_slice(lt.dst.fname.c_bytes());
    s.extend_from_slice(b"\n\nTransform_Type = Linear;\nLinear_Transform =\n");
    if lta.ltype == LINEAR_RAS_TO_RAS || lta.ltype == MNI_TRANSFORM_TYPE {
        let Some(m) = first_matrix(g, err, "ltaMNIwrite", lta, 3, 4)? else {
            return Ok(ERROR_BADPARM);
        };
        mni_rows(&mut s, m);
    } else if lta.ltype == LINEAR_VOX_TO_VOX {
        let vox_from_ras = extract_r_to_i(g, out, err, &lt.src)?;
        let tmp = matrix_multiply(g, out, err, lt.m_l.as_ref(), vox_from_ras.as_ref(), None)?
            .into_new();
        let ras_from_voxel = extract_i_to_r(g, out, err, &lt.dst)?;
        let ras_to_ras =
            matrix_multiply(g, out, err, Some(&ras_from_voxel), tmp.as_ref(), None)?.into_new();
        let Some(m) = ras_to_ras.as_ref() else {
            // a product of other sizes: FreeSurfer reads through the missing result
            outside(g, err, "ltaMNIwrite", "a transform without its matrix")?;
            return Ok(ERROR_BADPARM);
        };
        mni_rows(&mut s, m);
    }
    let _ = fp.write_all(&s);
    fp.close();
    Ok(NO_ERROR)
}

/// `ltaFSLwrite(lta, fname)`: a one-transform array of the first transform's matrix (a copy) and
/// geometries (assigned) and the array's type, converted to `FSLREG_TYPE` when it is another
/// ([`lta_change_type`], `FSLOUTPUTTYPE` from `env`), then its matrix's four rows (four `%13.8f`
/// numbers each with a space after, a newline after each). `NO_ERROR`; a file that cannot be
/// created: `ltaFSLwrite: could not open file <name>` as an error, `ERROR_NOFILE`; a type the
/// conversion leaves: `ltaFSLwrite: could not convert to FSL format` as an error and
/// `ERROR_BADPARM` (the file created, empty). FS-504.
fn lta_fsl_write(
    g: &mut Globals,
    out: &mut dyn Write,
    err: &mut dyn Write,
    env: &Environment,
    dir: Option<&Path>,
    lta: &Lta,
    fname: &str,
) -> Result<i32, Fatal> {
    let Some(mut fp) = create(g, dir, fname) else {
        log::error_printf(
            g,
            err,
            ERROR_NOFILE,
            &format!("ltaFSLwrite: could not open file {fname}"),
        );
        return Ok(ERROR_NOFILE);
    };
    let mut tmp = lta_alloc(g, out, err, 1, None)?;
    if lta.num_xforms <= 0 || lta.xforms.is_empty() {
        outside(g, err, "ltaFSLwrite", "an array without transforms")?;
        return Ok(ERROR_BADPARM);
    }
    let lt = &lta.xforms[0];
    tmp.xforms[0].m_l = match matrix_copy(g, out, err, lt.m_l.as_ref(), None)? {
        Ret::New(m) => Some(m),
        _ => None,
    };
    tmp.xforms[0].src.assign(g, &lt.src);
    tmp.xforms[0].dst.assign(g, &lt.dst);
    tmp.ltype = lta.ltype;
    if tmp.ltype != FSLREG_TYPE {
        lta_change_type(g, out, err, env, &mut tmp, FSLREG_TYPE)?;
    }
    if tmp.ltype != FSLREG_TYPE {
        log::error_printf(
            g,
            err,
            ERROR_BADPARM,
            "ltaFSLwrite: could not convert to FSL format",
        );
        return Ok(ERROR_BADPARM);
    }
    let Some(m) = first_matrix(g, err, "ltaFSLwrite", &tmp, 4, 4)? else {
        return Ok(ERROR_BADPARM);
    };
    let mut s: Vec<u8> = Vec::new();
    for i in 1..=4 {
        for j in 1..=4 {
            f13(&mut s, m.relt(i, j), b" ");
        }
        s.push(b'\n');
    }
    let _ = fp.write_all(&s);
    fp.close();
    Ok(NO_ERROR)
}

/// `LTAwriteEx(lta, fname)`, by the extension after the name's last `.` (any case) and the
/// array's type:
/// - `xfm`, or `MNI_TRANSFORM_TYPE`: MINC's `.xfm` (`ltaMNIwrite`);
/// - `dat` or `reg`, or `REGISTER_DAT` with any extension but `lta`: a `register.dat`
///   (`regio_write_register`: the subject, the first transform's source voxel sizes along x and z,
///   `fscale`, the matrix, `round`): `NO_ERROR`, or `ERROR_NOFILE` when it fails;
/// - `fslmat`, or `FSLREG_TYPE`: an FSL matrix (`ltaFSLwrite`);
/// - otherwise FreeSurfer's `.lta`: `# transform file <name>`, `# created by <user> on <date>`
///   (`USER`, else `LOGNAME`, else `UNKNOWN`; the date `currentDateTime`'s, with its override) and
///   an empty line, then `LTAprint`'s text; `NO_ERROR`, or for a file that cannot be created
///   `LTAwrite(<name>): can't create file` as an error and `ERROR_BADFILE`.
///
/// FS-504.
#[allow(clippy::too_many_arguments)]
pub fn lta_write_ex(
    g: &mut Globals,
    out: &mut dyn Write,
    err: &mut dyn Write,
    env: &Environment,
    dir: Option<&Path>,
    lta: &Lta,
    fname: &str,
) -> Result<i32, Fatal> {
    let ext = file_name_extension(g, fname);
    if stricmp(g, &ext, "XFM") == 0 || lta.ltype == MNI_TRANSFORM_TYPE {
        return lta_mni_write(g, out, err, dir, lta, fname);
    }
    if stricmp(g, &ext, "DAT") == 0
        || stricmp(g, &ext, "REG") == 0
        || (lta.ltype == REGISTER_DAT && stricmp(g, &ext, "LTA") != 0)
    {
        let Some(m) = first_matrix(g, err, "LTAwriteEx", lta, 3, 4)? else {
            return Ok(ERROR_BADPARM);
        };
        let src = &lta.xforms[0].src;
        let status = regio_write_register(
            g,
            out,
            err,
            dir,
            fname,
            Some(lta.subject.c_bytes()),
            src.xsize,
            src.zsize,
            lta.fscale,
            m,
            FLT2INT_ROUND,
        );
        return Ok(if status == 0 { NO_ERROR } else { ERROR_NOFILE });
    }
    if stricmp(g, &ext, "FSLMAT") == 0 || lta.ltype == FSLREG_TYPE {
        return lta_fsl_write(g, out, err, env, dir, lta, fname);
    }
    let Some(mut fp) = create(g, dir, fname) else {
        log::error_printf(
            g,
            err,
            ERROR_BADFILE,
            &format!("LTAwrite({fname}): can't create file"),
        );
        return Ok(ERROR_BADFILE);
    };
    let user = env
        .get("USER")
        .or_else(|| env.get("LOGNAME"))
        .map(|v| v.as_encoded_bytes().to_vec())
        .unwrap_or_else(|| b"UNKNOWN".to_vec());
    let mut s: Vec<u8> = Vec::new();
    s.extend_from_slice(b"# transform file ");
    s.extend_from_slice(fname.as_bytes());
    s.extend_from_slice(b"\n# created by ");
    s.extend_from_slice(&user);
    s.extend_from_slice(b" on ");
    s.extend_from_slice(current_date_time(env, true).as_bytes());
    s.extend_from_slice(b"\n\n");
    let _ = fp.write_all(&s);
    lta_print(g, err, &mut fp, lta)?;
    fp.close();
    Ok(NO_ERROR)
}

/// `LTAwrite(lta, fname)`: [`lta_write_ex`].
#[allow(clippy::too_many_arguments)]
pub fn lta_write(
    g: &mut Globals,
    out: &mut dyn Write,
    err: &mut dyn Write,
    env: &Environment,
    dir: Option<&Path>,
    lta: &Lta,
    fname: &str,
) -> Result<i32, Fatal> {
    lta_write_ex(g, out, err, env, dir, lta, fname)
}

/// `LTAread(fname)`: [`lta_read_ex`] (FreeSurfer returns `LTAreadEx`'s array before its older
/// code).
pub fn lta_read(
    g: &mut Globals,
    out: &mut dyn Write,
    err: &mut dyn Write,
    dir: Option<&Path>,
    fname: &str,
    io: &mut dyn LtaIo,
) -> Result<Option<Lta>, Fatal> {
    lta_read_ex(g, out, err, dir, fname, io)
}

/// `LTAdumpVolGeom(fp, vg)`: `valid  <n>`, `width  <n>`, `height <n>`, `depth  <n>`, the voxel
/// sizes (`xsize  <f>`, ...), the direction cosines (`xdc    <f> <f> <f>`, ...; `%f`) and `fname
/// <name>`, one per line. 0.
pub fn lta_dump_vol_geom(fp: &mut dyn Write, vg: &VolGeom) -> i32 {
    let f = |x: f32| fmt_f(f64::from(x), 0, 6);
    let mut s: Vec<u8> = Vec::new();
    s.extend_from_slice(format!("valid  {}\n", vg.valid).as_bytes());
    s.extend_from_slice(format!("width  {}\n", vg.width).as_bytes());
    s.extend_from_slice(format!("height {}\n", vg.height).as_bytes());
    s.extend_from_slice(format!("depth  {}\n", vg.depth).as_bytes());
    s.extend_from_slice(format!("xsize  {}\n", f(vg.xsize)).as_bytes());
    s.extend_from_slice(format!("ysize  {}\n", f(vg.ysize)).as_bytes());
    s.extend_from_slice(format!("zsize  {}\n", f(vg.zsize)).as_bytes());
    for (name, a, b, c) in [
        ("xdc", vg.x_r, vg.x_a, vg.x_s),
        ("ydc", vg.y_r, vg.y_a, vg.y_s),
        ("zdc", vg.z_r, vg.z_a, vg.z_s),
    ] {
        s.extend_from_slice(format!("{name}    {} {} {}\n", f(a), f(b), f(c)).as_bytes());
    }
    s.extend_from_slice(b"fname  ");
    s.extend_from_slice(vg.fname.c_bytes());
    s.push(b'\n');
    let _ = fp.write_all(&s);
    0
}
