"""mri_make_uchar as a black box: FreeSurfer 8.2.0's official program against a candidate, case by case.

An open probe (``README.md``): it writes seeded synthetic inputs (coronal MGZ volumes in
``float``, ``uchar``, ``short`` and ``int``, a three-frame one, one with NaNs and infinities, a
constant one, an empty one, one of large and negative values, one of odd dimensions, one voxel,
a NIfTI copy, an axial and a sagittal one; MNI transforms near the identity, the identity, far
away, with a NaN, cut short; linear transform arrays from scanner to scanner and from voxel to
voxel; a text file and a folder) into ``<workspace>/oracles/inputs/fs-make-uchar-prog/<seed>/``,
runs each case's command line through the official program
(``$FREESURFER_HOME/bin/mri_make_uchar``, found on the ``PATH`` by its name as
``mri_nu_correct.mni`` runs it) by the oracle-output cache at one thread, and through the
candidate (``--candidate``, a command line whose ``{mode}`` becomes ``reproduce`` and then
``fix``), each in a folder of its own (outputs are written there; ``=x`` copies an input there
first, for the calls that write over their input). Compared: the exit status, standard output
and error (the timing line's figures, ``--all-info``'s time, the case's folder and the
candidate's ``larmorx:`` notices aside) and every file written (FreeSurfer's provenance aside:
``larmorx_validation.freesurfer.files``). ``reproduce`` must give FreeSurfer's on every case;
``fix`` may differ only with a notice.

    python -P validation/investigations/freesurfer-mri-make-uchar-probe/compare.py --seed 1 \\
        --candidate '<program> --upstream-defects {mode} freesurfer mri_make_uchar'
"""

