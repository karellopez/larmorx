/* Prints CTN's data dictionary (dcmdict.c's tables, included here as the compiler sees them) as the
 * Rust table larmorx-io's dicom::dict carries: each group in the order DCM_LookupElement searches
 * them, each group's entries in order (a linear search, the first match wins), every tag with its
 * value representation (DCM_VALUEREPRESENTATION's number) and English description. Built and run by
 * gen_dict.sh against CTN 3.0.6 and against FreeSurfer 8.2.0's copy (the two must agree). */
#include "dcmdict.c"

int main(void) {
    unsigned long i, j;
    printf("// SPDX-License-Identifier: Apache-2.0 AND LicenseRef-CTN\n");
    printf("// Generated by validation/probes/fs-dicom/gen_dict.sh from CTN 3.0.6's dcmdict.c (the\n");
    printf("// RSNA and Washington University notice: crates/larmorx-io/PROVENANCE.md, NOTICE). Do not edit.\n");
    printf("//\n");
    printf("// Copyright (C) 1993, 1994, RSNA and Washington University. The notice's three paragraphs\n");
    printf("// are in crates/larmorx-io/src/dicom/mod.rs and in NOTICE.\n\n");
    printf("use super::dict::Entry;\n\n");
    printf("/// The groups in DCM_LookupElement's search order, each with its entries in order.\n");
    printf("pub(super) static GROUPS: &[(u16, &[Entry])] = &[\n");
    for (i = 0; i < sizeof(group_dictionary) / sizeof(group_dictionary[0]); i++) {
        printf("    (0x%04x, &[\n", group_dictionary[i].group);
        for (j = 0; j < group_dictionary[i].entries; j++) {
            DCMDICT *d = &group_dictionary[i].dict[j];
            const char *s = d->englishDescription;
            printf("        Entry { tag: 0x%08x, vr: %d, description: \"", d->tag, (int) d->representation);
            for (; *s; s++) {
                if (*s == '"' || *s == '\\') putchar('\\');
                putchar(*s);
            }
            printf("\" },\n");
        }
        printf("    ]),\n");
    }
    printf("];\n");
    return 0;
}
