"""Generates fs.gca's `cma_names.rs` (the table behind `cma_label_to_name`) from FreeSurfer
8.2.0's `utils/gca.cpp`: its chain of `if (label == <name>) return ("<text>");` tests, in their
order (the first equal label wins), the names being `include/cma.h`'s label constants (track C's
`larmorx_freesurfer_volume::cma`). Closed to FreeSurfer clean-room implementers.

    python3 -P validation/probes/fs-gcam/cma_names.py <workspace>/tags/freesurfer-8.2.0 \
        crates-freesurfer/larmorx-freesurfer-gca/src/cma_names.rs
"""

import re
import sys


def main() -> None:
    src, dst = sys.argv[1], sys.argv[2]
    lines = open(f"{src}/utils/gca.cpp", encoding="latin-1").read().split("\n")
    start = next(i for i, l in enumerate(lines) if l.startswith("const char *cma_label_to_name(int label)"))
    end = next(i for i in range(start, len(lines)) if lines[i] == "}")
    body = "\n".join(lines[start:end])
    pairs = re.findall(
        r'if \((?:label == (\w+)|(\w+) == label)\)\s*\{?\s*return \("([^"]*)"\);', body
    )
    tests = body.count("if (")
    if len(pairs) != tests:
        raise SystemExit(f"{len(pairs)} pairs for {tests} tests")
    out = [
        "// SPDX-License-Identifier: LicenseRef-FreeSurfer",
        "// Part of larmorx-freesurfer (FreeSurfer's licence; see crates-freesurfer/LICENSE). Copyright",
        "// 2026 Karel Lopez Vilaret.",
        "//! The names `cma_label_to_name` (`utils/gca.cpp` %d) returns, generated by" % (start + 1),
        "//! `validation/probes/fs-gcam/cma_names.py` from its chain of tests, in their order (the first",
        "//! equal label wins: several names share a number).",
        "#![allow(non_upper_case_globals)]",
        "",
        "use larmorx_freesurfer_volume::cma::*;",
        "",
        "/// `(label, name)` in `cma_label_to_name`'s order.",
        "pub const NAMES: &[(i32, &str)] = &[",
    ]
    for a, b, text in pairs:
        out.append(f'    ({a or b}, "{text}"),')
    out.append("];")
    out.append("")
    open(dst, "w").write("\n".join(out))
    print(f"{len(pairs)} names")


if __name__ == "__main__":
    main()
