"""Makes the probe's eigexp.rs (an experimental copy of larmorx_core::vnl_eigen with ORDER mutable)
from crates/larmorx-core/src/vnl_eigen.rs. Usage: mkexp.py <vnl_eigen.rs> <out>"""

import sys
from pathlib import Path

s = Path(sys.argv[1]).read_text()
s = s[: s.index("#[cfg(test)]\nmod tests")]
s = s.replace("crate::", "larmorx_core::")
old = "static ORDER: [u8; SITES] ="
assert old in s
s = s.replace(old, "pub static ORDER0: [u8; SITES] =")
s += """
/// The table the experiment changes, started from the port's.
pub static ORDER: [std::sync::atomic::AtomicU8; SITES] = [const { std::sync::atomic::AtomicU8::new(0) }; SITES];

/// Copies the port's table into [`ORDER`].
pub fn init() {
    for (a, &v) in ORDER.iter().zip(ORDER0.iter()) {
        a.store(v, std::sync::atomic::Ordering::Relaxed);
    }
}
"""
s = s.replace("    ORDER[site]\n", "    ORDER[site].load(std::sync::atomic::Ordering::Relaxed)\n")
s = s.replace("const SITES: usize", "pub const SITES: usize")
# no doc lints for an experiment
s = (
    "// SPDX-License-Identifier: Apache-2.0 AND BSD-3-Clause\n// GENERATED by mkexp.py from larmorx_core's vnl_eigen.rs (an experiment: ORDER mutable). Do not edit.\n#![allow(dead_code, unused_imports, clippy::all)]\n"
    + s.split("\n", 1)[1]
)
Path(sys.argv[2]).write_text(s)
print("OK")
