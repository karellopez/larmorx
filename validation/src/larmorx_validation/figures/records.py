"""Reading the committed records: validation records (``docs/validation/<suite>.json`` and
``.md``) and benchmark reports (``docs/benchmarks/<suite>.json``).

A record's JSON keeps each case's status; the numbers a figure needs beyond that (which cases
are bit-identical to the unmodified original, the original's thread band, per-category tables)
are in the Markdown record the same run wrote, in tables generated by the suite's code. They
are read here, by their column names, and a figure fails loudly when a table it needs is
missing rather than drawing something else.
"""

from __future__ import annotations

import hashlib
import json
import re
from collections import Counter
from dataclasses import dataclass, field
from pathlib import Path


@dataclass
class Table:
    """A Markdown table: its column names, its rows, the section it is in."""

    columns: list[str]
    rows: list[dict[str, str]]
    section: str = ""

    def column(self, name: str) -> list[str]:
        return [r[name] for r in self.rows]


@dataclass
class Record:
    """A validation record: the JSON and the Markdown of one parity run."""

    name: str
    path_json: Path
    path_md: Path
    data: dict
    text: str
    repo: Path
    tables: list[Table] = field(default_factory=list)

    @property
    def results(self) -> list[dict]:
        return self.data["results"]

    @property
    def summary(self) -> dict[str, int]:
        return self.data["summary"]

    @property
    def commit(self) -> str:
        return self.data.get("environment", {}).get("larmorx_commit") or "?"

    @property
    def generated(self) -> str:
        m = re.search(r"\*\*Generated:\*\* (\d{4}-\d{2}-\d{2})", self.text)
        return m.group(1) if m else "?"

    def table(self, *columns: str, section: str | None = None) -> Table:
        """The first table with all of ``columns`` (and in ``section``, if given)."""
        for t in self.tables:
            if all(c in t.columns for c in columns) and (
                section is None or section.lower() in t.section.lower()
            ):
                return t
        raise LookupError(f"{self.path_md.name}: no table with columns {columns}")

    def has_table(self, *columns: str) -> bool:
        try:
            self.table(*columns)
        except LookupError:
            return False
        return True

    def by_category(self) -> dict[str, Counter]:
        out: dict[str, Counter] = {}
        for r in self.results:
            out.setdefault(r["category"], Counter())[r["status"]] += 1
        return out

    def source(self) -> list[dict]:
        """How a figure's provenance names this record."""
        return [
            {
                "path": p.relative_to(self.repo).as_posix(),
                "sha256": hashlib.sha256(p.read_bytes()).hexdigest(),
                "generated": self.generated,
                "larmorx_commit": self.commit,
            }
            for p in (self.path_json, self.path_md)
        ]


def parse_tables(text: str) -> list[Table]:
    """Every GitHub-flavoured Markdown table in ``text``, with the heading above it."""
    tables: list[Table] = []
    section = ""
    lines = text.splitlines()
    i = 0
    while i < len(lines):
        line = lines[i]
        if line.startswith("#"):
            section = line.lstrip("#").strip()
        if (
            line.startswith("|")
            and i + 1 < len(lines)
            and re.fullmatch(r"\|(\s*:?-+:?\s*\|)+", lines[i + 1].strip())
        ):
            n = len(_cells(lines[i + 1]))
            columns = _cells(line)
            if len(columns) != n:
                # a header with unescaped pipes ("max |diff| / band"): cells end at " | "
                columns = [c.strip() for c in re.split(r"\s\|\s", line.strip()[1:-1].strip())]
            rows = []
            i += 2
            while i < len(lines) and lines[i].startswith("|"):
                cells = _cells(lines[i])
                rows.append(dict(zip(columns, cells, strict=False)))
                i += 1
            tables.append(Table(columns, rows, section))
            continue
        i += 1
    return tables


def _cells(line: str) -> list[str]:
    # split on | not preceded by a backslash
    parts = re.split(r"(?<!\\)\|", line.strip())[1:-1]
    return [p.strip().replace("\\|", "|") for p in parts]


def strip_code(s: str) -> str:
    return s.strip().strip("`")


def load(repo: Path, name: str) -> Record:
    j = repo / "docs" / "validation" / f"{name}.json"
    m = repo / "docs" / "validation" / f"{name}.md"
    data = json.loads(j.read_text(encoding="utf-8"))
    text = m.read_text(encoding="utf-8")
    return Record(name, j, m, data, text, repo, parse_tables(text))


@dataclass
class Bench:
    name: str
    path: Path
    data: dict
    repo: Path

    @property
    def results(self) -> list[dict]:
        return self.data["results"]

    def source(self) -> list[dict]:
        env = self.data.get("environment", {})
        return [
            {
                "path": self.path.relative_to(self.repo).as_posix(),
                "sha256": hashlib.sha256(self.path.read_bytes()).hexdigest(),
                "larmorx_commit": env.get("larmorx_commit"),
                "cpu": env.get("cpu"),
            }
        ]


def load_bench(repo: Path, name: str) -> Bench | None:
    p = repo / "docs" / "benchmarks" / f"{name}.json"
    if not p.is_file():
        return None
    return Bench(name, p, json.loads(p.read_text(encoding="utf-8")), repo)


def number(text: str) -> float:
    """The first number in ``text`` (``inf`` included); NaN if there is none."""
    m = re.search(r"[-+]?(?:inf|\d+(?:\.\d*)?(?:e[-+]?\d+)?)", text.replace("×", "x"), re.I)
    return float(m.group(0)) if m else float("nan")


def case_list(text: str) -> list[str]:
    """The case names quoted with backticks in ``text``."""
    return re.findall(r"`([^`\s]+/[^`\s]+)`", text)
